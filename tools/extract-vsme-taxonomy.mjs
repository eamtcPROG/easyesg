#!/usr/bin/env node
/**
 * Turns EFRAG's published VSME XBRL taxonomy package into a `config/seed/` artefact (task 33.1).
 *
 * **It is committed rather than run once and thrown away, for three reasons.** Task 33.3 registers
 * a *second* version from day one, so this runs at least twice before the feature is finished.
 * NFR-12's quarterly regulatory watch brings new VSME releases, and each is a re-extraction rather
 * than a hand edit of 143 elements. And a seed nobody can regenerate is a seed nobody can verify —
 * which is the whole reason task 29.3 sourced CAEM rather than composing it, and why that entry
 * calls a list from memory "the IDNO mistake with a thousand opportunities to make it".
 *
 *     node tools/extract-vsme-taxonomy.mjs <unpacked-package-dir> <version>
 *
 * **Regex over XML, deliberately, and bounded by assertions.** These files are machine-generated by
 * EFRAG's own tooling and this reads four attributes and one element text; a parser would be a
 * dependency in the root workspace for one script that runs quarterly. What makes that safe is the
 * checking below rather than the parsing: the run fails loudly if the element count, the concrete
 * count or the module coverage moves, so a shape this does not understand cannot pass silently.
 *
 * **Wording is NOT extracted.** OQ-43 narrowed config-as-data to *behaviour*: the taxonomy's shape
 * is data in the store, and its labels ship with the release in `packages/i18n`'s catalogues. Task
 * 33.2 owns that half, and pulling labels in here would put 24 languages of EFRAG's wording into a
 * store whose whole purpose is values that change without a redeploy.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const [, , packageDir, version] = process.argv;
if (!packageDir || !version) {
  console.error('usage: extract-vsme-taxonomy.mjs <unpacked-package-dir> <version>');
  process.exit(2);
}

/**
 * Locate the `vsme/<version>` directory inside the unpacked package, wherever it was unzipped.
 *
 * **The parent must be named `vsme`, not merely contain it.** The package ships three taxonomies
 * side by side — `vsme`, `waste` and `nace` — each with the same `<version>` directory beneath it,
 * and the archive's own folder is `VSME-XBRL-Taxonomy-May-2026`, so a substring test on the path
 * matches `waste/2026-05-01` first and reads the wrong schema. It failed loudly here because the
 * file names differ; a package where they did not would have been extracted silently and wrong.
 */
const findTaxonomyDir = (root) => {
  const stack = [root];
  while (stack.length > 0) {
    const dir = stack.pop();
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const child = join(dir, entry.name);
      if (entry.name === version && basename(dir) === 'vsme') return child;
      stack.push(child);
    }
  }
  throw new Error(`no vsme/${version} directory under ${root}`);
};

const dir = findTaxonomyDir(packageDir);
const xsd = readFileSync(join(dir, 'vsme-all.xsd'), 'utf8');
const presentation = readFileSync(join(dir, 'vsme-presentation.xml'), 'utf8');
const definition = readFileSync(join(dir, 'vsme-definition.xml'), 'utf8');

/** The published package every artefact below is derived from. */
const SOURCE = 'https://xbrl.efrag.org/downloads/vsme/VSME-XBRL-Taxonomy-May-2026.zip';

const attribute = (tag, name) => new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1] ?? null;

/**
 * XBRL's item types, mapped to the vocabulary a form and a validator actually branch on.
 *
 * **The unit-bearing types collapse to one `numeric` kind and keep their XBRL type beside it.** A
 * mass and a volume are the same control — a number with a unit — and which units are offered is
 * the taxonomy's business rather than the renderer's, so a screen that switched on `massItemType`
 * would need a new branch for every dimension EFRAG adds. An unmapped type is a hard failure, not
 * a default: a silent fallback is how a monetary field renders as free text.
 */
const KIND_BY_TYPE = {
  'xbrli:stringItemType': 'text',
  'dtr-types:textBlockItemType': 'text_block',
  'xbrli:booleanItemType': 'boolean',
  'xbrli:dateItemType': 'date',
  'xbrli:gYearItemType': 'year',
  'xbrli:monetaryItemType': 'monetary',
  'xbrli:decimalItemType': 'numeric',
  'dtr-types:percentItemType': 'percent',
  'dtr-types:massItemType': 'numeric',
  'dtr-types:volumeItemType': 'numeric',
  'dtr-types:areaItemType': 'numeric',
  'dtr-types:energyItemType': 'numeric',
  'dtr-types:ghgEmissionsItemType': 'numeric',
  'dtr-types:ghgEmissionsPerMonetaryItemType': 'numeric',
  'enum2:enumerationItemType': 'enumeration',
  'enum2:enumerationSetItemType': 'enumeration_set',
};

// ── Elements ────────────────────────────────────────────────────────────────────────────────────
const declarations = xsd.match(/<xs:element\b[^>]*\/>/g) ?? [];
const elements = new Map();
for (const tag of declarations) {
  const name = attribute(tag, 'name');
  if (!name) continue;
  elements.set(name, {
    type: attribute(tag, 'type'),
    abstract: attribute(tag, 'abstract') === 'true',
    substitutionGroup: attribute(tag, 'substitutionGroup'),
    periodType: attribute(tag, 'xbrli:periodType'),
    domain: attribute(tag, 'enum2:domain')?.replace(/^vsme:/, '') ?? null,
  });
}

// ── Modules, from the presentation roles' own definitions ────────────────────────────────────────
// `[1010] B1 - General information - Basis for Preparation` — the module is the standard's, stated
// by EFRAG in the role rather than inferred by us from element names.
const moduleByRole = new Map();
const roleTypes = xsd.match(/<link:roleType\b[\s\S]*?<\/link:roleType>/g) ?? [];
for (const block of roleTypes) {
  const uri = attribute(block, 'roleURI');
  const definition = /<link:definition>([^<]*)<\/link:definition>/.exec(block)?.[1] ?? '';
  // **Every presentation role is kept, module or not.** Three of them — *Environment / Social /
  // Governance - Other and/or entity specific information* — carry no `B`/`C` prefix because the
  // standard's catch-all disclosures belong to a pillar rather than a numbered module. Filtering
  // on the prefix dropped their three elements silently, which the count assertion below now makes
  // impossible; what they get is `module: null` and the role's own words, rather than a 21st
  // module invented here to give them somewhere to sit.
  const module = /^\[\d+\]\s+([BC]\d{1,2})\b/.exec(definition)?.[1] ?? null;
  if (uri && definition) moduleByRole.set(uri, { module, definition });
}

// ── Presentation: which module an element belongs to, and in what order ─────────────────────────
const placement = new Map();
const links = presentation.match(/<link:presentationLink\b[\s\S]*?<\/link:presentationLink>/g) ?? [];
for (const link of links) {
  const role = moduleByRole.get(attribute(link, 'xlink:role'));
  if (!role) continue;

  const labelToName = new Map();
  for (const loc of link.match(/<link:loc\b[^>]*\/>/g) ?? []) {
    const name = attribute(loc, 'xlink:href')?.split('#vsme_')[1];
    const label = attribute(loc, 'xlink:label');
    if (name && label) labelToName.set(label, name);
  }

  for (const arc of link.match(/<link:presentationArc\b[^>]*\/>/g) ?? []) {
    const name = labelToName.get(attribute(arc, 'xlink:to') ?? '');
    if (!name || placement.has(name)) continue;
    placement.set(name, {
      module: role.module,
      section: role.definition,
      order: Number.parseFloat(attribute(arc, 'order') ?? '0'),
      parent: labelToName.get(attribute(arc, 'xlink:from') ?? '') ?? null,
    });
  }
}

// ── Dimensions ──────────────────────────────────────────────────────────────────────────────────
/**
 * The XBRL Dimensions chain. **Element→axis is walked one `definitionLink` at a time; every other
 * fact about an axis is collected across all of them** — and getting that split wrong is what the
 * first two attempts each did, in opposite directions.
 *
 * Within one link EFRAG states two things that only meet through the link itself:
 *
 *     <X>Abstract --all--------------------> <X>Table --hypercube-dimension--> <X>Axis
 *     <X>Abstract --domain-member----------> <X>LineItems --domain-member----> the concrete elements
 *
 * The `all` arc starts at an **abstract**, never at a reportable element, so asking "which
 * hypercubes name this element" answers nothing for any element in the taxonomy. What connects them
 * is that both arcs leave the same abstract inside the same role — so the attachment walk is scoped
 * to the link. Scoped globally it would attach B3's energy axis to B8's headcount, because
 * `domain-member` is also how the enumeration domains are drawn and they share the same arcrole.
 *
 * An axis's own facts are the other way round. `dimension-default` lives in its own
 * `defaults-99000` link, and `ReportingScopesAxis` is drawn in two roles while
 * `CountryOfEmploymentContractAxis` is named in one link and given its domain in another — so a
 * first-link-wins read left four of the eight axes with no domain and all eight with no default,
 * which looked exactly like a taxonomy that declares neither.
 *
 * **This half is not optional, and its absence is what the first draft got wrong.** §7.3's
 * `report_disclosure_value` is keyed on `(report_id, element_key, dimension_key, ordinal)`, so a
 * disclosure is an element *and* its dimension — and VSME reports energy exactly that way: there is
 * no `EnergyConsumptionFromRenewableSources` element, there is `EnergyConsumptionFromFuels` taken
 * along a `RenewableEnergyMember` / `NonRenewableEnergyMember` axis. An artefact carrying elements
 * alone would leave task 34's store unable to say what a row means and task 36 unable to draw it.
 */
const ARCROLE = 'http://xbrl.org/int/dim/arcrole';

/**
 * An `xlink:href` resolved to the taxonomy that declares it.
 *
 * **A reference outside `vsme` is carried, not dropped.** B7's waste axis takes its domain from the
 * sibling `waste` taxonomy shipped in the same package, and the earlier `split('#vsme_')[1]` read
 * that as an unresolvable label and silently gave the axis no domain at all — an artefact that
 * looked complete and left the standard's largest classification out of B7.
 */
const resolveName = (href) => {
  if (!href) return null;
  const [path, fragment] = href.split('#');
  if (!fragment) return null;
  const separator = fragment.indexOf('_');
  if (separator < 0) return null;
  const prefix = fragment.slice(0, separator);
  const external = /(?:^|\/)([a-z-]+)\/([\d-]+)\/[^/]+$/.exec(path ?? '');
  return {
    name: fragment.slice(separator + 1),
    taxonomy: prefix,
    version: prefix === 'vsme' ? version : (external?.[2] ?? null),
  };
};

/** Every `definitionLink`, resolved from xlink labels to taxonomy-qualified names. */
const definitionLinks = (linkbase) =>
  (linkbase.match(/<link:definitionLink\b[\s\S]*?<\/link:definitionLink>/g) ?? []).map((link) => {
    const named = new Map();
    for (const loc of link.match(/<link:loc\b[^>]*\/>/g) ?? []) {
      const resolved = resolveName(attribute(loc, 'xlink:href'));
      const label = attribute(loc, 'xlink:label');
      if (resolved && label) named.set(label, resolved);
    }
    const arcs = [];
    for (const arc of link.match(/<link:definitionArc\b[^>]*\/>/g) ?? []) {
      const arcrole = attribute(arc, 'xlink:arcrole');
      const from = named.get(attribute(arc, 'xlink:from') ?? '');
      const to = named.get(attribute(arc, 'xlink:to') ?? '');
      if (arcrole?.startsWith(`${ARCROLE}/`) && from && to) {
        arcs.push({ role: arcrole.slice(ARCROLE.length + 1), from, to });
      }
    }
    return arcs;
  });

const definitionArcSets = definitionLinks(definition);
const everyArc = definitionArcSets.flat();

/** Everything reachable from `root` by `domain-member`. Depth-first, cycle-safe. */
const descend = (root, arcs, seen = new Set([root])) =>
  arcs
    .filter((arc) => arc.role === 'domain-member' && arc.from.name === root && !seen.has(arc.to.name))
    .flatMap((arc) => (seen.add(arc.to.name), [arc.to.name, ...descend(arc.to.name, arcs, seen)]));

/**
 * Typed axes take an arbitrary identifier rather than a member — a site, a subsidiary, a material.
 * They carry `xbrldt:typedDomainRef` in the schema and correctly have no domain, so the assertion
 * below must not demand one of them. It is a real distinction for task 36: a typed axis renders as
 * a repeating group the reporter adds rows to, an explicit one as a choice among known members.
 */
const typedAxes = new Set(
  declarations
    .filter((tag) => attribute(tag, 'xbrldt:typedDomainRef'))
    .map((tag) => attribute(tag, 'name')),
);

const axes = new Map();
for (const arc of everyArc) {
  if (arc.role !== 'hypercube-dimension') continue;
  const axis = arc.to.name;
  if (axes.has(axis)) continue;

  const domain = everyArc.find((a) => a.role === 'dimension-domain' && a.from.name === axis)?.to ?? null;
  axes.set(axis, {
    typed: typedAxes.has(axis),
    domain: domain?.name ?? null,
    // Where the domain is another taxonomy's, say so — B7's waste categories are the EU List of
    // Waste, published and versioned by EFRAG separately from VSME itself.
    ...(domain && domain.taxonomy !== 'vsme'
      ? { domainTaxonomy: domain.taxonomy, domainVersion: domain.version }
      : {}),
    // The member a fact carrying no dimension is taken to mean — the total line, in every VSME
    // case. Without it a report storing only the breakdown looks like it is missing its total, and
    // one storing only the total looks undimensioned.
    defaultMember:
      everyArc.find((a) => a.role === 'dimension-default' && a.from.name === axis)?.to.name ?? null,
    members: domain ? descend(domain.name, everyArc) : [],
  });
}

/** Element → the axes it is reported along, attached per link (see the header). */
const elementAxes = new Map();
for (const arcs of definitionArcSets) {
  const hypercubes = arcs.filter((arc) => arc.role === 'all');
  if (hypercubes.length === 0) continue;

  const linkAxes = hypercubes.flatMap(({ to: hypercube }) =>
    arcs
      .filter((arc) => arc.role === 'hypercube-dimension' && arc.from.name === hypercube.name)
      .map((arc) => arc.to.name),
  );

  // The `all` source is the abstract the line items also hang from, so descending it reaches every
  // element the hypercube governs — including the line-items holder, which is abstract and drops
  // out downstream on the same concreteness test every other element passes.
  for (const { from: abstract } of hypercubes) {
    for (const element of descend(abstract.name, arcs)) {
      if (!elementAxes.has(element)) elementAxes.set(element, new Set());
      for (const axis of linkAxes) elementAxes.get(element).add(axis);
    }
  }
}

const axesForElement = (name) => [...(elementAxes.get(name) ?? [])];

// ── The external domain: the EU List of Waste ───────────────────────────────────────────────────
/**
 * B7's waste axis takes its domain from the `waste` taxonomy EFRAG ships beside VSME in the same
 * package — 975 members of the EU List of Waste, versioned on its own.
 *
 * **It is emitted as its own artefact rather than inlined into the VSME one**, and that follows
 * DR-4 rather than tidiness: version is a data dimension, and a single file carrying two
 * independently-versioned standards would make a waste-list revision indistinguishable from a VSME
 * release. The store is generic (AD-3, AD-4), so a second artefact costs a JSON file and no code.
 *
 * **Labels ARE extracted here, where the VSME elements' deliberately are not**, and the line
 * between them is the one OQ-43 draws. A VSME element's label is product UI text — the wording on a
 * form field — so it ships in `packages/i18n`'s catalogues with the release. A waste category's
 * name is the *value's own name*, part of the datum like a country's, which is why the CAEM
 * classifier carries its labels in `config/seed/nace-code.md.json` too. **EFRAG publishes English
 * only for this taxonomy**, so `ro` and `ru` are outstanding and platform-authored — T-14's standing
 * for the Russian VSME labels, reaching one taxonomy further. Never machine-translated.
 */
const externalTaxonomy = (taxonomy, taxonomyVersion, root) => {
  const externalDir = join(dir, '..', '..', taxonomy, taxonomyVersion);
  const arcs = definitionLinks(
    readFileSync(join(externalDir, `${taxonomy}-definition.xml`), 'utf8'),
  ).flat();
  const labelFile = readFileSync(join(externalDir, `${taxonomy}-label-en.xml`), 'utf8');

  // `xlink:label` → the standard label's text, joined to a `loc` through the labelArc.
  const labelText = new Map();
  for (const tag of labelFile.match(/<link:label\b[^>]*>[\s\S]*?<\/link:label>/g) ?? []) {
    const id = attribute(tag, 'xlink:label');
    const text = /<link:label\b[^>]*>([\s\S]*?)<\/link:label>/.exec(tag)?.[1] ?? '';
    if (id) labelText.set(id, text.trim());
  }
  const locName = new Map();
  for (const loc of labelFile.match(/<link:loc\b[^>]*\/>/g) ?? []) {
    const resolved = resolveName(attribute(loc, 'xlink:href'));
    const id = attribute(loc, 'xlink:label');
    if (resolved && id) locName.set(id, resolved.name);
  }
  const labels = new Map();
  for (const arc of labelFile.match(/<link:labelArc\b[^>]*\/>/g) ?? []) {
    const name = locName.get(attribute(arc, 'xlink:from') ?? '');
    const text = labelText.get(attribute(arc, 'xlink:to') ?? '');
    if (name && text) labels.set(name, text);
  }

  const members = arcs.filter((arc) => arc.role === 'domain-member');
  const parentOf = new Map(members.map((arc) => [arc.to.name, arc.from.name]));
  const arcOrder = new Map();
  for (const [index, arc] of members.entries()) arcOrder.set(arc.to.name, index);

  /**
   * EFRAG's label is the XBRL *concept's* label, not the value's name:
   * `20 03 01 - Non-Hazardous - Mixed municipal waste [member]`. Three of those four parts are
   * scaffolding — the code and the hazard flag are already columns here, and **`[member]` is an
   * XBRL-internal notion the root CLAUDE.md forbids from any surface a person reads**. Left alone,
   * a picker would render *"20 03 01 — 20 03 01 - Non-Hazardous - Mixed municipal waste [member]"*.
   *
   * Stripped by **proving** each part rather than by pattern: the prefix must be this member's own
   * code and its own hazard word, so a label EFRAG formats differently survives untouched instead
   * of being silently truncated. Casing is left exactly as published — the chapter titles are upper
   * case in the List of Waste itself, and re-casing them is an editorial decision belonging to
   * whoever authors the `ro` and `ru` labels, not to a regex here.
   */
  const humanLabel = (raw, code, hazard) => {
    let text = raw.replace(/\s*\[member\]$/, '');
    for (const part of [code, hazard]) {
      if (part && text.startsWith(`${part} - `)) text = text.slice(part.length + 3);
    }
    return text.trim();
  };

  const entries = descend(root, arcs).map((name) => {
    // `W-010101-Non-Hazardous-WastesFromMineralMetalliferousExcavationMember` — the EU code and the
    // hazard classification are stated in the member's own name, which is how the standard carries
    // them. A chapter or sub-chapter has a code and no hazard classification, which is why the
    // flag is omitted rather than defaulted to `false`: *not stated at this level* and *classified
    // as non-hazardous* are different answers, and B7 reports on the second.
    const parsed = /^W-(\d+)-(Hazardous|Non-Hazardous)?/.exec(name);
    // Rendered the way the List of Waste itself writes it — `01 01 01`, in pairs.
    const formattedCode = (parsed?.[1] ?? '').replace(/(\d\d)(?=\d)/g, '$1 ');
    return [
      name,
      {
        code: formattedCode,
        ...(parsed?.[2] ? { hazardous: parsed[2] === 'Hazardous' } : {}),
        parent: parentOf.get(name) === root ? null : (parentOf.get(name) ?? null),
        order: arcOrder.get(name) ?? 0,
        labels: {
          ...(labels.has(name)
            ? { en: humanLabel(labels.get(name), formattedCode, parsed?.[2] ?? null) }
            : {}),
        },
      },
    ];
  });

  const unnamed = entries.filter(([, e]) => !e.code || Object.keys(e.labels).length === 0);
  if (unnamed.length > 0) {
    console.error(`${unnamed.length} ${taxonomy} member(s) with no code or no label:`);
    for (const [name] of unnamed.slice(0, 10)) console.error(`  ${name}`);
    process.exit(1);
  }

  return {
    taxonomy,
    version: taxonomyVersion,
    source: SOURCE,
    root,
    members: Object.fromEntries(entries.sort(([a], [b]) => a.localeCompare(b))),
  };
};

const externals = new Map();
for (const [, axis] of axes) {
  if (!axis.domainTaxonomy || externals.has(axis.domainTaxonomy)) continue;
  externals.set(
    axis.domainTaxonomy,
    externalTaxonomy(axis.domainTaxonomy, axis.domainVersion, axis.domain),
  );
}

/**
 * **An explicit axis with no members is a read this script got wrong, not a taxonomy that offers no
 * choices.** It is the dimension half of the "nothing reportable may be dropped" rule below, and it
 * earned its place three times in one sitting: first-link-wins emptied four axes, the `#vsme_` split
 * emptied B7's, and this form is what then found that B7's domain lives in a linkbase this script
 * had not opened. Each produced an artefact that parsed, validated and was quietly missing a
 * dimension the standard requires.
 *
 * An axis whose domain is another taxonomy's satisfies it only when **this run also emitted that
 * taxonomy** — a reference is not a member list, and recording one without the other is the same
 * silent gap wearing a citation.
 */
const emptyAxes = [...axes.entries()].filter(
  ([, a]) =>
    !a.typed &&
    a.members.length === 0 &&
    // The domain root is not a member of itself, so the question is whether this run emitted that
    // taxonomy rooted at this axis's domain — not whether the root appears in its own member list.
    !(a.domainTaxonomy && externals.get(a.domainTaxonomy)?.root === a.domain),
);
if (emptyAxes.length > 0) {
  console.error('explicit axis with no members — the walk is wrong, not the taxonomy:');
  for (const [name, a] of emptyAxes) console.error(`  ${name} (domain ${a.domain ?? 'unresolved'})`);
  process.exit(1);
}


// ── The artefact ────────────────────────────────────────────────────────────────────────────────
const concrete = [...elements.entries()].filter(
  ([, e]) => !e.abstract && e.substitutionGroup === 'xbrli:item',
);
const reportable = concrete.filter(([name]) => placement.has(name));

/**
 * **Nothing reportable may be dropped, and this is the assertion that makes the regex safe.**
 *
 * Every concrete item must be placed by the presentation linkbase. When it is not, the cause is
 * this script failing to understand a role rather than the taxonomy failing to present an element
 * — which is exactly what happened on the first run, where a module-prefix filter silently lost the
 * three *Other and/or entity specific information* disclosures. A count that moves is a release to
 * read, not a default to take.
 */
const dropped = concrete.filter(([name]) => !placement.has(name)).map(([name]) => name);
if (dropped.length > 0) {
  console.error(`${dropped.length} concrete element(s) reached no presentation role:`);
  for (const name of dropped) console.error(`  ${name}`);
  process.exit(1);
}

const unmapped = reportable.filter(([, e]) => !KIND_BY_TYPE[e.type]);
if (unmapped.length > 0) {
  console.error('unmapped XBRL types — add them to KIND_BY_TYPE rather than defaulting:');
  for (const [name, e] of unmapped) console.error(`  ${name}: ${e.type}`);
  process.exit(1);
}

const payload = {
  taxonomy: 'vsme',
  version,
  source: SOURCE,
  modules: [...new Set(reportable.map(([name]) => placement.get(name).module))]
    .filter((module) => module !== null)
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true })),
  /** Each reporting axis and the members it admits, so a form can offer them without a code change. */
  axes: Object.fromEntries([...axes.entries()].sort(([a], [b]) => a.localeCompare(b))),
  elements: Object.fromEntries(
    reportable
      .map(([name, e]) => {
        const at = placement.get(name);
        return [
          name,
          {
            module: at.module,
            section: at.section,
            order: at.order,
            parent: at.parent,
            kind: KIND_BY_TYPE[e.type],
            xbrlType: e.type,
            periodType: e.periodType,
            ...(e.domain ? { domain: e.domain } : {}),
            // The axes this element is reported along, if any. Empty is the ordinary case; a
            // non-empty list is what makes `report_disclosure_value.dimension_key` meaningful.
            ...(axesForElement(name).length > 0 ? { axes: axesForElement(name) } : {}),
          },
        ];
      })
      .sort(([a], [b]) => a.localeCompare(b)),
  ),
};

const target = `config/seed/vsme-taxonomy.${version}.json`;
writeFileSync(target, `${JSON.stringify(payload, null, 2)}\n`);

for (const [name, artefact] of externals) {
  const file = `config/seed/vsme-${name}-classification.${artefact.version}.json`;
  writeFileSync(file, `${JSON.stringify(artefact, null, 2)}\n`);
  console.log(`${file}`);
  console.log(`  members        ${Object.keys(artefact.members).length}`);
  console.log(
    `  hazardous      ${Object.values(artefact.members).filter((m) => m.hazardous === true).length}`,
  );
}

console.log(`${target}`);
